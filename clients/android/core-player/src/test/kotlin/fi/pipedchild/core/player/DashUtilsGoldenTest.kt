package fi.pipedchild.core.player

import android.net.Uri
import androidx.media3.exoplayer.dash.manifest.DashManifest
import androidx.media3.exoplayer.dash.manifest.DashManifestParser
import androidx.media3.exoplayer.dash.manifest.Representation
import fi.pipedchild.core.model.PipedStream
import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import java.io.ByteArrayInputStream
import java.io.File

/**
 * Golden comparison against the REAL DashUtils.js: the expected MPD in
 * clients/contracts/golden/dashutils_expected.mpd was generated by running
 * the web client's own src/utils/DashUtils.js (node + fast-xml-parser) on
 * dashutils_input.json. Both MPDs are parsed through Media3's
 * DashManifestParser and compared structurally, so any fidelity drift in the
 * Kotlin port fails this test.
 *
 * Known, documented deviation (asserted nowhere below by design): the port
 * omits AdaptationSet id, which Media3 requires to be numeric.
 */
@RunWith(RobolectricTestRunner::class)
class DashUtilsGoldenTest {

    private val json = Json { ignoreUnknownKeys = true }

    private fun golden(name: String): String =
        File(File("..", ".."), "contracts/golden/$name").readText()

    private fun parse(mpd: String): DashManifest = DashManifestParser().parse(
        Uri.parse("https://piped-child.test/golden.mpd"),
        ByteArrayInputStream(mpd.toByteArray(Charsets.UTF_8)),
    )

    /** Canonical summary: per adaptation set, mimeType + sorted reps of
     *  (id, codecs, bandwidth, width, height, baseUrl). */
    private fun canonical(manifest: DashManifest): List<Pair<String, List<String>>> =
        (0 until manifest.periodCount).flatMap { manifest.getPeriod(it).adaptationSets }.map { set ->
            val mime = set.representations.first().format.sampleMimeType.orEmpty()
            val reps = set.representations.map { rep: Representation ->
                listOf(
                    rep.format.id,
                    rep.format.codecs,
                    rep.format.bitrate,
                    rep.format.width,
                    rep.format.height,
                    rep.format.frameRate.toInt(),
                    rep.baseUrls.single().url,
                ).joinToString("|")
            }.sorted()
            mime to reps
        }.sortedBy { it.first }

    @Test
    fun `kotlin port output matches real DashUtils js output structurally`() {
        val input = json.decodeFromString<List<PipedStream>>(golden("dashutils_input.json"))
        val kotlinMpd = DashManifestGenerator.generate(input, durationSeconds = 212)
        val jsMpd = golden("dashutils_expected.mpd")

        // Both parse through the exact parser ExoPlayer uses
        val kotlinManifest = parse(kotlinMpd)
        val jsManifest = parse(jsMpd)

        assertEquals(canonical(jsManifest), canonical(kotlinManifest))

        // Segment ranges preserved identically (Media3 needs them for init/index)
        val ranges = Regex("""indexRange="[^"]+"|range="[^"]+"""")
        assertEquals(
            ranges.findAll(jsMpd).map { it.value }.toList(),
            ranges.findAll(kotlinMpd).map { it.value }.toList(),
        )

        // Envelope and attribute-level equality (parser ignores these)
        val envelope = Regex("""(profiles|minBufferTime|type|mediaPresentationDuration)="[^"]+"""")
        assertEquals(
            envelope.findAll(jsMpd).map { it.value }.toSet(),
            envelope.findAll(kotlinMpd).map { it.value }.toSet(),
        )
        // maxPlayoutRate / scanType are invisible to Media3's parser; compare
        // them textually so the port cannot drift from the web client
        for (attr in listOf("""maxPlayoutRate="1"""", """scanType="progressive""")) {
            assertEquals(
                "occurrences of $attr",
                Regex(Regex.escape(attr)).findAll(jsMpd).count(),
                Regex(Regex.escape(attr)).findAll(kotlinMpd).count(),
            )
        }
    }
}
